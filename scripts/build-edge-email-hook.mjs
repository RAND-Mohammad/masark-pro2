import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const inputs = [
  'supabase/functions/_shared/email-idempotency.ts',
  'supabase/functions/_shared/auth-email-templates.ts',
  'supabase/functions/send-auth-email/handler.ts',
  'supabase/functions/send-auth-email/index.ts',
];
const sources = await Promise.all(inputs.map(path => readFile(new URL(path, root), 'utf8')));
// Keep the pinned npm import, but inline local imports for the dashboard editor.
const body = sources.map(source => source.replace(/^import .* from ['"]\..*['"];?\r?\n/gm, '')).join('\n');
const output = new URL('generated-artifacts/send-auth-email/index.ts', root);
await mkdir(new URL('./', output), { recursive: true });
await writeFile(output, `// Generated by npm run build:edge-email-hook; edit the source files instead.\n${body}`);
console.log(`Supabase dashboard source: ${fileURLToPath(output)}`);
